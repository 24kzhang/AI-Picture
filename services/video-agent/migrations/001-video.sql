CREATE TABLE IF NOT EXISTS video_project (
 id CHAR(36) PRIMARY KEY, space_id BIGINT NULL, owner_id BIGINT NOT NULL,
 name VARCHAR(200) NOT NULL, revision INT NOT NULL DEFAULT 1,
 lease_user_id BIGINT NULL, lease_session VARCHAR(100) NULL, lease_epoch BIGINT NOT NULL DEFAULT 0,
 lease_until DATETIME(3) NULL, created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), INDEX(space_id, owner_id)
) ENGINE=InnoDB CHARACTER SET utf8mb4;
CREATE TABLE IF NOT EXISTS video_revision (
 project_id CHAR(36) NOT NULL, revision INT NOT NULL, source JSON NOT NULL,
 author_id BIGINT NOT NULL, message VARCHAR(300) NOT NULL, created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 PRIMARY KEY(project_id, revision)
) ENGINE=InnoDB CHARACTER SET utf8mb4;
CREATE TABLE IF NOT EXISTS video_quota (
 scope VARCHAR(80) PRIMARY KEY, bytes BIGINT NOT NULL DEFAULT 0, video_count INT NOT NULL DEFAULT 0
) ENGINE=InnoDB CHARACTER SET utf8mb4;
CREATE TABLE IF NOT EXISTS video_object (
 scope VARCHAR(80) NOT NULL, digest CHAR(64) NOT NULL, object_key VARCHAR(400) NOT NULL,
 size BIGINT NOT NULL, PRIMARY KEY(scope, digest)
) ENGINE=InnoDB CHARACTER SET utf8mb4;
CREATE TABLE IF NOT EXISTS video_asset (
 id CHAR(36) PRIMARY KEY, project_id CHAR(36) NOT NULL, name VARCHAR(200) NOT NULL, kind VARCHAR(20) NOT NULL,
 metadata JSON NOT NULL, created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), INDEX(project_id)
) ENGINE=InnoDB CHARACTER SET utf8mb4;
CREATE TABLE IF NOT EXISTS video_record (
 id CHAR(36) PRIMARY KEY, project_id CHAR(36) NOT NULL, revision INT NOT NULL,
 space_id BIGINT NULL, owner_id BIGINT NOT NULL, name VARCHAR(200) NOT NULL, metadata JSON NOT NULL,
 review_status INT NOT NULL DEFAULT 0, deleted BOOLEAN NOT NULL DEFAULT FALSE,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), INDEX(space_id, deleted, created_at)
) ENGINE=InnoDB CHARACTER SET utf8mb4;
CREATE TABLE IF NOT EXISTS video_run (
 id CHAR(36) PRIMARY KEY, project_id CHAR(36) NOT NULL, user_id BIGINT NOT NULL,
 revision INT NOT NULL, kind VARCHAR(30) NOT NULL, status VARCHAR(30) NOT NULL,
 request JSON NOT NULL, result JSON NULL, error TEXT NULL, cancelled BOOLEAN NOT NULL DEFAULT FALSE,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), INDEX(project_id, created_at)
) ENGINE=InnoDB CHARACTER SET utf8mb4;
CREATE TABLE IF NOT EXISTS video_step (
 run_id CHAR(36) NOT NULL, step_id VARCHAR(80) NOT NULL, provider VARCHAR(50) NOT NULL,
 status VARCHAR(30) NOT NULL, build_id VARCHAR(120) NULL, remote_task_id VARCHAR(120) NULL,
 request JSON NOT NULL, result JSON NULL, error TEXT NULL, PRIMARY KEY(run_id, step_id)
) ENGINE=InnoDB CHARACTER SET utf8mb4;
CREATE TABLE IF NOT EXISTS video_event (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, run_id CHAR(36) NOT NULL, type VARCHAR(50) NOT NULL,
 data JSON NOT NULL, created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), INDEX(run_id, id)
) ENGINE=InnoDB CHARACTER SET utf8mb4;
CREATE TABLE IF NOT EXISTS video_idempotency (
 project_id CHAR(36) NOT NULL, request_key VARCHAR(100) NOT NULL, digest CHAR(64) NOT NULL,
 response JSON NOT NULL, PRIMARY KEY(project_id, request_key)
) ENGINE=InnoDB CHARACTER SET utf8mb4;
